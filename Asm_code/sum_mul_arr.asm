.data

A: 10, 5, 12, -3, 8, 15, -7, 2, 10, -4, 6

B: 10, 52, 122, -31, 111, 5, -45, 4, 15, -4, 1

.text

LOAD R1, [A] ; Загружаем количество элементов
MOV R2, A    ; Загружаем адрес массива A
MOV R3, B    ; Загружаем адрес массива B

MOV R7, 0    ; Зануляем аккумулятор
MOV R8, 0

M1:
ADD R2, 4    ; Переходим к следующему элементу массива A
ADD R3, 4    ; Переходим к следующему элементу массива B

LOAD R4, [R2]   ; Загружаем элемент массива A
LOAD R6, [R3]   ; Загружаем элемент массива B

MUL R4, R6      ; Произведение элементов массивов

ADD R7, R4  ; Сумма всех произведений
ADC R8, R5  ; Здесь учитывается флаг переноса прошлой операции

SUB R1, 1        ; Уменьшаем счётчик
JNZ M1           ; Повторяем, пока счётчик не равен нулю

HALT


; R1	Количество оставшихся элементов
; R2	Текущий адрес элемента массива A
; R3	Текущий адрес элемента массива B
; R4	Первый 32-битный множитель, затем младшая часть произведения
; R5	Старшая часть произведения
; R6	Второй 32-битный множитель
; R7	Младшая часть аккумулятора
; R8	Старшая часть аккумулятора