.data

array: 10, 5, 12, -3, 8, 15, -7, 2, 10, -4, 6

.text

LOAD R1, [array] ; Загружаем количество элементов
MOV R2, array    ; Загружаем адрес массива
MOV R4, 0        ; Зануляем аккумулятор 

M1:
ADD R2, 4        ; Переходим к следующему элементу
LOAD R3, [R2]    ; Загружаем элемент массива
ADD R4, R3       ; Добавляем его к сумме
SUB R1, 1        ; Уменьшаем счётчик
JNZ M1           ; Повторяем, пока счётчик не равен нулю

HALT